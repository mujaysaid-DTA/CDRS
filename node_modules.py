import os
import shutil


def nuke_dependencies():
    base_path = os.getcwd()

    print("☢️  NUKING NODE_MODULES (Preparing for clean deploy)...")

    # List of folders to destroy
    targets = [
        os.path.join(base_path, 'node_modules'),
        os.path.join(base_path, 'frontend', 'node_modules'),
        os.path.join(base_path, 'backend', 'node_modules')
    ]

    for target in targets:
        if os.path.exists(target):
            print(f"   🔥 Deleting: {target}")
            try:
                # Windows sometimes locks files, so we try/catch
                shutil.rmtree(target, ignore_errors=True)
                print("      Deleted.")
            except Exception as e:
                print(f"      ⚠️  Error deleting (might be open in VS Code): {e}")
        else:
            print(f"   (Clean) {target} not found.")

    print("\n✅ Folders removed locally.")
    print("👉 NOW: Run the Git commands below immediately to clean GitHub!")


if __name__ == "__main__":
    nuke_dependencies()